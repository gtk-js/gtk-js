import { readFileSync, writeFileSync } from "node:fs";
import { parseStyleScheme } from "./src/parse-style-scheme.ts";

const upstream = new URL("../../upstream/gtksourceview/", import.meta.url).pathname;

// The schemes GtkSourceView bundles: those its resources list (testdark.xml is a test file).
const resources = readFileSync(`${upstream}gtksourceview/gtksourceview.gresource.xml`, "utf8");
const files = [...resources.matchAll(/>\.\.\/data\/styles\/([^<]+\.xml)</g)].map((m) => m[1]!);
if (!files.length) throw new Error("no style schemes in gtksourceview.gresource.xml");

const schemes = files.map((file) => {
  try {
    return parseStyleScheme(readFileSync(`${upstream}data/styles/${file}`, "utf8"));
  } catch (error) {
    throw new Error(`could not load style scheme file '${file}': ${(error as Error).message}`);
  }
});

const out = `// Generated by build.ts from upstream/gtksourceview/data/styles/*.xml. Do not edit.
import type { GtkSourceStyleSchemeData } from "./style-scheme-data.ts";

/** The ids of the style schemes GtkSourceView bundles. */
export type GtkSourceBundledStyleSchemeId = ${schemes.map((s) => JSON.stringify(s.id)).join(" | ")};

/** The style schemes GtkSourceView bundles, by id. */
export const styleSchemes: Readonly<Record<GtkSourceBundledStyleSchemeId, GtkSourceStyleSchemeData>> = ${JSON.stringify(
  Object.fromEntries(schemes.map((scheme) => [scheme.id, scheme])),
  null,
  2,
)};
`;
writeFileSync(new URL("src/schemes.ts", import.meta.url).pathname, out);
console.log(`Built ${schemes.length} style schemes: ${schemes.map((s) => s.id).join(", ")}`);
